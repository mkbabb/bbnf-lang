#[derive(Debug, Error)]
pub enum CodegenError {
    #[error(transparent)]
    Grammar(#[from] grammar::GrammarError),
    #[error(transparent)]
    Pass(#[from] passes::PassError),
    #[error("missing generated file `{0}`")]
    MissingFile(String),
    #[error("generated file `{0}` differs")]
    DifferentFile(String),
    #[error("unexpected generated file `{0}`")]
    UnexpectedFile(String),
    #[error("lowering failed: {0}")]
    Lowering(String),
    #[error("{code}: {path}@{offset} source_hash={source_hash}")]
    UnsupportedRuntimeConstruct {
        code: &'static str,
        path: String,
        offset: usize,
        source_hash: String,
    },
    #[error(transparent)]
    Io(#[from] std::io::Error),
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EmittedSource {
    files: BTreeMap<String, String>,
}

impl EmittedSource {
    pub fn files(&self) -> impl Iterator<Item = (&str, &str)> {
        self.files
            .iter()
            .map(|(path, source)| (path.as_str(), source.as_str()))
    }

    pub fn get(&self, path: &str) -> Option<&str> {
        self.files.get(path).map(String::as_str)
    }

    pub fn write_to_dir(&self, output_dir: impl AsRef<Path>) -> Result<(), CodegenError> {
        let output_dir = output_dir.as_ref();
        std::fs::create_dir_all(output_dir)?;
        for (path, source) in &self.files {
            let file = output_dir.join(path);
            std::fs::write(file, source)?;
        }
        Ok(())
    }

    pub fn check_dir(&self, output_dir: impl AsRef<Path>) -> Result<(), CodegenError> {
        let output_dir = output_dir.as_ref();
        for (path, source) in &self.files {
            let file = output_dir.join(path);
            let actual = std::fs::read_to_string(&file)
                .map_err(|_| CodegenError::MissingFile(path.clone()))?;
            if actual != *source {
                return Err(CodegenError::DifferentFile(path.clone()));
            }
        }
        for entry in std::fs::read_dir(output_dir)? {
            let entry = entry?;
            let path = entry.path();
            if path.extension().and_then(|ext| ext.to_str()) != Some("rs") {
                continue;
            }
            let Some(file_name) = path.file_name().and_then(|name| name.to_str()) else {
                continue;
            };
            if self.files.contains_key(file_name) {
                continue;
            }
            let actual = std::fs::read_to_string(&path)?;
            if actual.starts_with(GENERATED_HEADER) {
                return Err(CodegenError::UnexpectedFile(file_name.to_string()));
            }
        }
        Ok(())
    }
}

const GENERATED_HEADER: &str = "// @generated by skinny bbnf-codegen; do not edit by hand.";

pub fn emit_from_source(grammar_name: &str, source: &str) -> Result<EmittedSource, CodegenError> {
    let grammar = grammar::parse_grammar(grammar_name, source)?;
    let output = passes::compile(&grammar)?;
    emit_with_layout(
        &output.backend_ir,
        &output.layout_facts.backend_shape,
        &output.layout_facts.cost_facts,
        &output.layout_facts.per_grammar_policy,
        &output.layout_facts.same_substrate_union,
        &output.diagnostics,
    )
}

pub fn emit(backend: &BackendIr) -> Result<EmittedSource, CodegenError> {
    let _ = backend;
    Err(CodegenError::Lowering(
        "W7 fail-closed: emit() requires pass-produced backend shape, active-cost, and CSP facts"
            .to_string(),
    ))
}

pub fn emit_runtime_profile(grammar_name: &str) -> Result<EmittedSource, CodegenError> {
    let profile = grammar_profile::select_runtime_profile_for_name(grammar_name)?;
    runtime_generator::emit_profile_only(profile)
}

pub fn runtime_profile_expected_files(profile_id: &str) -> Result<Vec<&'static str>, CodegenError> {
    let profile = grammar_profile::select_runtime_profile_for_name(profile_id)?;
    Ok(profile.generated_runtime_files().to_vec())
}

pub fn emit_typed_from_source(
    grammar_name: &str,
    source: &str,
    schema: &DirectSchemaSet,
) -> Result<EmittedSource, CodegenError> {
    let grammar = grammar::parse_grammar(grammar_name, source)?;
    let output = passes::compile(&grammar)?;
    emit_typed_with_layout(
        &output.backend_ir,
        &output.layout_facts.backend_shape,
        &output.layout_facts.cost_facts,
        &output.layout_facts.per_grammar_policy,
        &output.layout_facts.same_substrate_union,
        &output.diagnostics,
        schema,
    )
}

fn emit_with_layout(
    backend: &BackendIr,
    backend_shape: &std::collections::HashMap<RuleId, BackendShape>,
    cost_facts: &std::collections::HashMap<RuleId, CostFacts>,
    per_grammar_policy: &std::collections::HashMap<RuleId, PerGrammarPolicyFacts>,
    same_substrate_union: &std::collections::HashMap<RuleId, SameSubstrateUnionFacts>,
    diagnostics: &[passes::diagnostics::PassDiagnostic],
) -> Result<EmittedSource, CodegenError> {
    let profile = grammar_profile::select_runtime_profile(backend)?;
    let lowered = lower::lower_to_rust(
        backend,
        &lower::LowerCtx {
            backend_shape,
            cost_facts,
            per_grammar_policy,
            same_substrate_union,
            diagnostics,
        },
    )
    .map_err(CodegenError::Lowering)?;
    let sink_only = lowered.sink_only_program.as_ref().ok_or_else(|| {
        CodegenError::Lowering(
            "BackendIr did not contain DirectBuild sink-only program".to_string(),
        )
    })?;
    runtime_generator::emit_compiled(profile, sink_only)
}

fn emit_typed_with_layout(
    backend: &BackendIr,
    backend_shape: &std::collections::HashMap<RuleId, BackendShape>,
    cost_facts: &std::collections::HashMap<RuleId, CostFacts>,
    per_grammar_policy: &std::collections::HashMap<RuleId, PerGrammarPolicyFacts>,
    same_substrate_union: &std::collections::HashMap<RuleId, SameSubstrateUnionFacts>,
    diagnostics: &[passes::diagnostics::PassDiagnostic],
    schema: &DirectSchemaSet,
) -> Result<EmittedSource, CodegenError> {
    grammar_profile::select_runtime_profile(backend)?;
    let lowered = lower::lower_to_rust(
        backend,
        &lower::LowerCtx {
            backend_shape,
            cost_facts,
            per_grammar_policy,
            same_substrate_union,
            diagnostics,
        },
    )
    .map_err(CodegenError::Lowering)?;
    let sink_only = lowered.sink_only_program.as_ref().ok_or_else(|| {
        CodegenError::Lowering(
            "BackendIr did not contain DirectBuild sink-only program".to_string(),
        )
    })?;
    let typed =
        lower::schema_direct::lower_program(sink_only, schema).map_err(CodegenError::Lowering)?;
    let mut files = BTreeMap::new();
    files.insert(
        format!("{}.rs", schema.module_name),
        json_typed_direct::render(&typed).map_err(CodegenError::Lowering)?,
    );
    Ok(EmittedSource { files })
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CostFactsSnapshot {
    pub grammar: String,
    pub cost_facts: std::collections::BTreeMap<String, CostFacts>,
    pub diagnostics: Vec<DiagnosticSnapshot>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DiagnosticSnapshot {
    pub code: String,
    pub rule: Option<RuleId>,
    pub message: String,
}

pub fn cost_facts_from_source(
    grammar_name: &str,
    source: &str,
) -> Result<CostFactsSnapshot, CodegenError> {
    let grammar = grammar::parse_grammar(grammar_name, source)?;
    let output = passes::compile(&grammar)?;
    let cost_facts = output
        .layout_facts
        .cost_facts
        .iter()
        .map(|(rule_id, facts)| (rule_id.0.to_string(), facts.clone()))
        .collect();
    let diagnostics = output
        .diagnostics
        .iter()
        .map(|diagnostic| DiagnosticSnapshot {
            code: diagnostic.code().to_string(),
            rule: diagnostic.rule,
            message: diagnostic.message.clone(),
        })
        .collect();
    Ok(CostFactsSnapshot {
        grammar: output.grammar.name,
        cost_facts,
        diagnostics,
    })
}

