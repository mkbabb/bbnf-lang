//! SK-V19.W6a — generate `PRODUCTION_MANIFEST_TABLE` from manifest
//! metadata, not a grammar-named const in the generic crate.
//!
//! The per-grammar codegen substrate binding is **data** that lives in
//! `[package.metadata.bbnf-strategy]` of this crate's own `Cargo.toml`
//! (sk-v27 LW2.TOPO-4b: never the workspace root, which no package
//! carries). The generic `bbnf-ir` crate carries the generic mechanism
//! only (the `ManifestStrategyEntry` row shape + the
//! `for_grammar_with_manifest` resolver). The grammar-named rows are
//! emitted here, at build time, into
//! `$OUT_DIR/production_manifest_table.rs`, which `registry/strategy.rs`
//! `include!`s. No grammar name appears in `crates/ir/src` (Lock 14).

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let cargo_toml = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("Cargo.toml");

    println!("cargo:rerun-if-changed={}", cargo_toml.display());

    let toml_text = fs::read_to_string(&cargo_toml).unwrap_or_else(|e| {
        panic!(
            "crates/ir build.rs: cannot read {}: {e}",
            cargo_toml.display()
        )
    });

    let doc: toml::Value =
        toml::from_str(&toml_text).expect("crates/ir build.rs: Cargo.toml is not valid TOML");

    let grammars = doc
        .get("package")
        .and_then(|p| p.get("metadata"))
        .and_then(|m| m.get("bbnf-strategy"))
        .and_then(|s| s.get("grammars"))
        .and_then(|g| g.as_array())
        .expect(
            "crates/ir build.rs: missing [package.metadata.bbnf-strategy] grammars array \
             in crates/ir/Cargo.toml",
        );

    let mut rows = String::new();
    rows.push_str(
        "// @generated by crates/ir/build.rs from [package.metadata.bbnf-strategy].\n\
         // Do not edit by hand; edit the crates/ir/Cargo.toml table instead.\n",
    );
    rows.push_str("pub const PRODUCTION_MANIFEST_TABLE: &[ManifestStrategyEntry] = &[\n");

    for (i, entry) in grammars.iter().enumerate() {
        let idents = entry
            .get("idents")
            .and_then(|v| v.as_array())
            .unwrap_or_else(|| panic!("bbnf-strategy grammar[{i}] missing `idents` array"));
        let builder = entry
            .get("rust_builder_path")
            .and_then(|v| v.as_str())
            .unwrap_or_else(|| panic!("bbnf-strategy grammar[{i}] missing `rust_builder_path`"));
        let document = entry
            .get("rust_document_path")
            .and_then(|v| v.as_str())
            .unwrap_or_else(|| panic!("bbnf-strategy grammar[{i}] missing `rust_document_path`"));

        let ident_lits = idents
            .iter()
            .map(|v| {
                let s = v
                    .as_str()
                    .unwrap_or_else(|| panic!("bbnf-strategy grammar[{i}] ident is not a string"));
                format!("{s:?}")
            })
            .collect::<Vec<_>>()
            .join(", ");

        rows.push_str("    ManifestStrategyEntry {\n");
        rows.push_str(&format!("        idents: &[{ident_lits}],\n"));
        rows.push_str(&format!("        rust_builder_path: {builder:?},\n"));
        rows.push_str(&format!("        rust_document_path: {document:?},\n"));
        rows.push_str("    },\n");
    }
    rows.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let out_path = out_dir.join("production_manifest_table.rs");
    fs::write(&out_path, rows).expect("crates/ir build.rs: cannot write generated manifest table");
}
