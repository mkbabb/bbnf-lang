use std::fmt::Write as _;

use serde::Serialize;

use super::budget::CompileOptions;
use super::diagnostic::{Diagnostic, DiagnosticCode, StageResult};
use super::event::{EVENT_SCHEMA, ScalarEventPlan};
use super::lower::{LoweringPlan, PlanOp, PlanRecordSlot, RegexPlanData};
use super::source::Revision;

const GENERATED_SCHEMA: &str = "bbnf.generated-rust.v5";

/// One deterministic, direct Rust parser product.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GeneratedModule {
    revision: Revision,
    source: String,
    manifest: String,
}

impl GeneratedModule {
    pub(crate) fn emit(
        events: &ScalarEventPlan,
        lowering: &LoweringPlan,
        options: CompileOptions,
    ) -> StageResult<Self> {
        if events.revision() != lowering.revision() {
            return StageResult::rejected(Diagnostic::new(
                DiagnosticCode::RevisionMismatch,
                0,
                0,
                "emitter inputs carry different revisions",
            ));
        }
        let mut emitter = RustEmitter::new(events, lowering, options);
        if let Err(failure) = emitter.write_module() {
            let (code, message) = match failure {
                EmitFailure::Invariant(message) => (DiagnosticCode::InternalInvariant, message),
                EmitFailure::OutputBudget { limit } => (
                    DiagnosticCode::GeneratedSourceTooLarge,
                    format!("generated Rust exceeded the configured limit of {limit} bytes"),
                ),
            };
            return StageResult::rejected(Diagnostic::new(code, 0, 0, message));
        }

        let revision = events.revision();
        let source = emitter.source.into_string();
        let source_digest = blake3::hash(source.as_bytes()).to_hex().to_string();
        let manifest = serde_json::to_string(&GeneratedManifest {
            schema: GENERATED_SCHEMA,
            event_schema: events.schema(),
            revision: revision.hex(),
            source_blake3: source_digest,
            source_bytes: source.len(),
            nodes: lowering.nodes().len(),
            rules: lowering.rules().len(),
            regexes: lowering.regexes().len(),
            transforms: events.transforms().len(),
            fields: lowering.fields().len(),
        })
        .expect("generated manifest fields are serializable");

        StageResult::accepted(Self {
            revision,
            source,
            manifest,
        })
    }

    pub const fn revision(&self) -> Revision {
        self.revision
    }

    pub fn source(&self) -> &str {
        &self.source
    }

    pub fn manifest(&self) -> &str {
        &self.manifest
    }
}

#[derive(Serialize)]
struct GeneratedManifest<'a> {
    schema: &'static str,
    event_schema: &'a str,
    revision: String,
    source_blake3: String,
    source_bytes: usize,
    nodes: usize,
    rules: usize,
    regexes: usize,
    transforms: usize,
    fields: usize,
}

struct RustEmitter<'a> {
    events: &'a ScalarEventPlan,
    plan: &'a LoweringPlan,
    options: CompileOptions,
    source: BoundedSource,
}

impl<'a> RustEmitter<'a> {
    fn new(events: &'a ScalarEventPlan, plan: &'a LoweringPlan, options: CompileOptions) -> Self {
        Self {
            events,
            plan,
            options,
            source: BoundedSource::new(options.generated_bytes),
        }
    }

    fn write_module(&mut self) -> Result<(), EmitFailure> {
        for node in self.plan.nodes() {
            if matches!(node.op(), PlanOp::Choice(children) if children.is_empty()) {
                return Err(EmitFailure::Invariant(format!(
                    "sealed lowering plan contains empty choice at node {}",
                    node.id().index()
                )));
            }
        }

        writeln!(
            self.source,
            "// @generated by bbnf; schema={GENERATED_SCHEMA}; revision={}",
            self.events.revision().hex()
        )
        .unwrap();
        self.source.push_str("use core::cell::Cell;\n");
        self.write_parse_that_imports();
        self.source.push('\n');
        writeln!(
            self.source,
            "pub const EVENT_SCHEMA: &str = {EVENT_SCHEMA:?};"
        )
        .unwrap();
        writeln!(
            self.source,
            "pub const REVISION: &str = {:?};",
            self.events.revision().hex()
        )
        .unwrap();
        self.source
            .push_str("const _: () = assert!(parse_that::KERNEL_ABI == 2);\n");
        writeln!(
            self.source,
            "const MAX_INPUT_BYTES: usize = {};",
            self.options.runtime.input_bytes
        )
        .unwrap();
        writeln!(
            self.source,
            "const MAX_NESTING: usize = {};",
            self.options.runtime.nesting
        )
        .unwrap();
        writeln!(
            self.source,
            "const MAX_LOGICAL_EVENTS: usize = {};",
            self.options.runtime.logical_events
        )
        .unwrap();
        writeln!(
            self.source,
            "const MAX_WORK: usize = {};\n",
            self.options.runtime.work
        )
        .unwrap();

        self.write_event_surface();
        self.write_transform_surface();
        self.write_field_surface();
        self.ensure_output_budget()?;
        for (index, regex) in self.plan.regexes().iter().enumerate() {
            self.write_regex(index, regex);
            self.ensure_output_budget()?;
        }
        for node in self.plan.nodes() {
            self.write_node(node.id().index(), node.op());
            self.ensure_output_budget()?;
        }
        for rule in self.plan.rules() {
            self.write_rule(rule.id().index(), rule.root().index());
            self.ensure_output_budget()?;
        }
        self.write_public_surface();
        self.ensure_output_budget()?;
        Ok(())
    }

    fn ensure_output_budget(&self) -> Result<(), EmitFailure> {
        if self.source.exceeded() {
            Err(EmitFailure::OutputBudget {
                limit: self.options.generated_bytes,
            })
        } else {
            Ok(())
        }
    }

    fn write_parse_that_imports(&mut self) {
        let mut imports = vec![
            "eof",
            "sequence",
            "EventSink",
            "Fault",
            "Input",
            "ModuleResult",
            "NoSink",
            "ResourceKind",
            "Run",
            "Step",
        ];
        if self
            .plan
            .nodes()
            .iter()
            .any(|node| matches!(node.op(), PlanOp::Choice(_)))
        {
            imports.push("choice");
        }
        if self
            .plan
            .nodes()
            .iter()
            .any(|node| matches!(node.op(), PlanOp::Literal(_)))
        {
            imports.push("literal");
        }
        if !self.plan.regexes().is_empty() {
            imports.extend(["regex", "RegexPlan", "RegexTerminal"]);
        }
        if self
            .plan
            .nodes()
            .iter()
            .any(|node| matches!(node.op(), PlanOp::Repeat { .. }))
        {
            imports.push("repeat");
        }
        imports.sort_unstable();
        writeln!(self.source, "use parse_that::{{{}}};", imports.join(", ")).unwrap();
    }

    fn write_event_surface(&mut self) {
        self.source.push_str(
            "#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n\
             #[non_exhaustive]\n\
             pub enum EventKind {\n\
                 EnterRule,\n\
                 LeaveRule,\n\
                 EnterField,\n\
                 LeaveField,\n\
                 Literal,\n\
                 Regex,\n\
                 ChoiceBranch,\n\
                 RepeatCount,\n\
                 Transform,\n\
                 EndInput,\n\
             }\n\n\
             #[derive(Clone, Copy, Debug, Eq, PartialEq)]\n\
             pub struct ScalarEvent {\n\
                 kind: EventKind,\n\
                 rule: Option<u32>,\n\
                 node: Option<u32>,\n\
                 field: Option<u32>,\n\
                 transform: Option<u32>,\n\
                 start: u32,\n\
                 end: u32,\n\
                 value: u32,\n\
             }\n\n\
             impl ScalarEvent {\n\
                 pub const fn kind(&self) -> EventKind { self.kind }\n\
                 pub const fn rule(&self) -> Option<u32> { self.rule }\n\
                 pub const fn node(&self) -> Option<u32> { self.node }\n\
                 pub const fn field(&self) -> Option<u32> { self.field }\n\
                 pub const fn transform(&self) -> Option<u32> { self.transform }\n\
                 pub const fn start(&self) -> u32 { self.start }\n\
                 pub const fn end(&self) -> u32 { self.end }\n\
                 pub const fn value(&self) -> u32 { self.value }\n\
             }\n\n\
             #[derive(Clone, Debug)]\n\
             pub struct EventBuffer<'i> {\n\
                 revision: &'static str,\n\
                 source: Input<'i>,\n\
                 events: Vec<ScalarEvent>,\n\
             }\n\n\
             impl<'i> EventBuffer<'i> {\n\
                 fn new(source: Input<'i>) -> Self {\n\
                     Self { revision: REVISION, source, events: Vec::new() }\n\
                 }\n\n\
                 pub const fn revision(&self) -> &'static str {\n\
                     self.revision\n\
                 }\n\n\
                 pub const fn source(&self) -> Input<'i> {\n\
                     self.source\n\
                 }\n\n\
                 pub fn events(&self) -> &[ScalarEvent] {\n\
                     &self.events\n\
                 }\n\n\
                 pub fn into_stream(self) -> EventStream<'i> {\n\
                     EventStream {\n\
                         revision: self.revision,\n\
                         source: self.source,\n\
                         events: self.events,\n\
                     }\n\
                 }\n\
             }\n\n\
             impl EventSink for EventBuffer<'_> {\n\
                 type Event = ScalarEvent;\n\n\
                 fn len(&self) -> usize {\n\
                     self.events.len()\n\
                 }\n\n\
                 fn truncate(&mut self, len: usize) {\n\
                     self.events.truncate(len);\n\
                 }\n\n\
                 fn push(&mut self, event: Self::Event) {\n\
                     self.events.push(event);\n\
                 }\n\
             }\n\n\
             #[derive(Clone, Debug)]\n\
             pub struct EventStream<'i> {\n\
                 revision: &'static str,\n\
                 source: Input<'i>,\n\
                 events: Vec<ScalarEvent>,\n\
             }\n\n\
             impl<'i> EventStream<'i> {\n\
                 pub const fn revision(&self) -> &'static str { self.revision }\n\
                 pub const fn source(&self) -> Input<'i> { self.source }\n\
                 pub fn events(&self) -> &[ScalarEvent] { &self.events }\n\
                 pub fn into_parts(self) -> (&'static str, Input<'i>, Vec<ScalarEvent>) {\n\
                     (self.revision, self.source, self.events)\n\
                 }\n\
             }\n\n\
             #[derive(Clone, Copy, Debug, Eq, PartialEq)]\n\
             #[non_exhaustive]\n\
             pub enum RawSourceSpanNormalization {\n\
                 OriginalInputByteOffsets,\n\
             }\n\n\
             #[derive(Clone, Copy, Debug, Eq, PartialEq)]\n\
             #[non_exhaustive]\n\
             pub enum RecoveryPolicy {\n\
                 Disabled,\n\
             }\n\n\
             #[derive(Clone, Copy, Debug, Eq, PartialEq)]\n\
             #[non_exhaustive]\n\
             pub enum TransactionalErrorPolicy {\n\
                 RollbackAllEventsOnMismatchOrFault,\n\
             }\n\n\
             pub const RAW_SOURCE_SPAN_NORMALIZATION: RawSourceSpanNormalization =\n\
                 RawSourceSpanNormalization::OriginalInputByteOffsets;\n\
             pub const RECOVERY_POLICY: RecoveryPolicy = RecoveryPolicy::Disabled;\n\
             pub const TRANSACTIONAL_ERROR_POLICY: TransactionalErrorPolicy =\n\
                 TransactionalErrorPolicy::RollbackAllEventsOnMismatchOrFault;\n\n\
             #[derive(Clone, Copy, Debug, Eq, PartialEq)]\n\
             #[non_exhaustive]\n\
             pub struct LimitsConfig {\n\
                 input_bytes: usize,\n\
                 nesting: usize,\n\
                 logical_events: usize,\n\
                 work: usize,\n\
             }\n\n\
             impl Default for LimitsConfig {\n\
                 fn default() -> Self {\n\
                     Self {\n\
                         input_bytes: MAX_INPUT_BYTES,\n\
                         nesting: MAX_NESTING,\n\
                         logical_events: MAX_LOGICAL_EVENTS,\n\
                         work: MAX_WORK,\n\
                     }\n\
                 }\n\
             }\n\n\
             impl LimitsConfig {\n\
                 pub const fn input_bytes(&self) -> usize { self.input_bytes }\n\
                 pub const fn nesting(&self) -> usize { self.nesting }\n\
                 pub const fn logical_events(&self) -> usize { self.logical_events }\n\
                 pub const fn work(&self) -> usize { self.work }\n\
                 pub const fn with_input_bytes(mut self, limit: usize) -> Self {\n\
                     self.input_bytes = limit;\n\
                     self\n\
                 }\n\
                 pub const fn with_nesting(mut self, limit: usize) -> Self {\n\
                     self.nesting = limit;\n\
                     self\n\
                 }\n\
                 pub const fn with_logical_events(mut self, limit: usize) -> Self {\n\
                     self.logical_events = limit;\n\
                     self\n\
                 }\n\
                 pub const fn with_work(mut self, limit: usize) -> Self {\n\
                     self.work = limit;\n\
                     self\n\
                 }\n\
                 fn bounded(self) -> Self {\n\
                     Self {\n\
                         input_bytes: self.input_bytes.min(MAX_INPUT_BYTES),\n\
                         nesting: self.nesting.min(MAX_NESTING),\n\
                         logical_events: self.logical_events.min(MAX_LOGICAL_EVENTS),\n\
                         work: self.work.min(MAX_WORK),\n\
                     }\n\
                 }\n\
             }\n\n\
             struct Limits {\n\
                 config: LimitsConfig,\n\
                 depth: Cell<usize>,\n\
                 work: Cell<usize>,\n\
             }\n\n\
             impl Limits {\n\
                 fn new(config: LimitsConfig) -> Self {\n\
                     Self {\n\
                         config,\n\
                         depth: Cell::new(0),\n\
                         work: Cell::new(0),\n\
                     }\n\
                 }\n\
             }\n\n\
             fn resource_fault<'i, T, S: EventSink<Event = ScalarEvent>>(\n\
                 run: &Run<'i, S>,\n\
                 kind: ResourceKind,\n\
                 limit: usize,\n\
             ) -> Step<'i, T> {\n\
                 Step::Fault(Fault::ResourceLimit { at: run.cursor(), kind, limit })\n\
             }\n\n\
             fn charge_work<'i, S: EventSink<Event = ScalarEvent>>(\n\
                 run: &Run<'i, S>,\n\
                 limits: &Limits,\n\
             ) -> Step<'i, ()> {\n\
                 let work = limits.work.get();\n\
                 if work >= limits.config.work {\n\
                     return resource_fault(run, ResourceKind::Work, limits.config.work);\n\
                 }\n\
                 limits.work.set(work + 1);\n\
                 Step::Matched(())\n\
             }\n\n\
             fn with_depth<'i, T, S, F>(\n\
                 run: &mut Run<'i, S>,\n\
                 limits: &Limits,\n\
                 parser: F,\n\
             ) -> Step<'i, T>\n\
             where\n\
                 S: EventSink<Event = ScalarEvent>,\n\
                 F: FnOnce(&mut Run<'i, S>) -> Step<'i, T>,\n\
             {\n\
                 let depth = limits.depth.get();\n\
                 if depth >= limits.config.nesting {\n\
                     return resource_fault(run, ResourceKind::Nesting, limits.config.nesting);\n\
                 }\n\
                 limits.depth.set(depth + 1);\n\
                 let outcome = parser(run);\n\
                 limits.depth.set(depth);\n\
                 outcome\n\
             }\n\n\
             fn emit_event<'i, S, F>(\n\
                 run: &mut Run<'i, S>,\n\
                 limits: &Limits,\n\
                 event: F,\n\
             ) -> Step<'i, ()>\n\
             where\n\
                 S: EventSink<Event = ScalarEvent>,\n\
                 F: FnOnce() -> ScalarEvent,\n\
             {\n\
                 let logical_events = run.sink().len();\n\
                 if logical_events >= limits.config.logical_events {\n\
                     return resource_fault(\n\
                         run,\n\
                         ResourceKind::Events,\n\
                         limits.config.logical_events,\n\
                     );\n\
                 }\n\
                 run.emit_with(event);\n\
                 Step::Matched(())\n\
             }\n\n\
             struct EventIdentity {\n\
                 rule: Option<u32>,\n\
                 node: Option<u32>,\n\
                 field: Option<u32>,\n\
                 transform: Option<u32>,\n\
             }\n\n\
             const fn identity(\n\
                 rule: Option<u32>,\n\
                 node: Option<u32>,\n\
                 field: Option<u32>,\n\
                 transform: Option<u32>,\n\
             ) -> EventIdentity {\n\
                 EventIdentity { rule, node, field, transform }\n\
             }\n\n\
             fn event(\n\
                 kind: EventKind,\n\
                 identity: EventIdentity,\n\
                 start: usize,\n\
                 end: usize,\n\
                 value: u32,\n\
             ) -> ScalarEvent {\n\
                 ScalarEvent {\n\
                     kind,\n\
                     rule: identity.rule,\n\
                     node: identity.node,\n\
                     field: identity.field,\n\
                     transform: identity.transform,\n\
                     start: u32::try_from(start).expect(\"input bound checked before parsing\"),\n\
                     end: u32::try_from(end).expect(\"input bound checked before parsing\"),\n\
                     value,\n\
                 }\n\
             }\n\n",
        );
    }

    fn write_transform_surface(&mut self) {
        self.source.push_str(
            "#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n\
             pub struct TransformDescriptor {\n\
                 id: u32,\n\
                 name: &'static str,\n\
             }\n\n\
             impl TransformDescriptor {\n\
                 pub const fn id(&self) -> u32 { self.id }\n\
                 pub const fn name(&self) -> &'static str { self.name }\n\
             }\n\n\
             pub const TRANSFORMS: &[TransformDescriptor] = &[\n",
        );
        for transform in self.events.transforms() {
            writeln!(
                self.source,
                "    TransformDescriptor {{ id: {}, name: {:?} }},",
                transform.id().index(),
                transform.name(),
            )
            .unwrap();
        }
        self.source.push_str("];\n\n");
    }

    fn write_field_surface(&mut self) {
        self.source.push_str(
            "#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n\
             pub struct FieldDescriptor {\n\
                 id: u32,\n\
                 owner_rule: u32,\n\
                 source_slot: u32,\n\
                 child_node: u32,\n\
                 semantic_type: u32,\n\
                 name: &'static str,\n\
             }\n\n\
             impl FieldDescriptor {\n\
                 pub const fn id(&self) -> u32 { self.id }\n\
                 pub const fn owner_rule(&self) -> u32 { self.owner_rule }\n\
                 pub const fn source_slot(&self) -> u32 { self.source_slot }\n\
                 pub const fn child_node(&self) -> u32 { self.child_node }\n\
                 pub const fn semantic_type(&self) -> u32 { self.semantic_type }\n\
                 pub const fn name(&self) -> &'static str { self.name }\n\
             }\n\n\
             pub const FIELDS: &[FieldDescriptor] = &[\n",
        );
        for field in self.plan.fields() {
            writeln!(
                self.source,
                "    FieldDescriptor {{ id: {}, owner_rule: {}, source_slot: {}, child_node: {}, semantic_type: {}, name: {:?} }},",
                field.id().index(),
                field.owner().index(),
                field.slot(),
                field.child().index(),
                field.semantic_type().index(),
                field.name(),
            )
            .unwrap();
        }
        self.source.push_str("];\n\n");
    }

    fn write_regex(&mut self, index: usize, regex: &RegexPlanData) {
        write!(
            self.source,
            "const REGEX_{index}_BYTE_CLASSES: [u8; 256] = "
        )
        .unwrap();
        write_slice(&mut self.source, regex.byte_classes());
        self.source.push_str(";\n");
        write!(
            self.source,
            "const REGEX_{index}_TRANSITIONS: [u32; {}] = ",
            regex.transitions().len()
        )
        .unwrap();
        write_slice(&mut self.source, regex.transitions());
        self.source.push_str(";\n");
        write!(
            self.source,
            "const REGEX_{index}_ACCEPTING: [bool; {}] = ",
            regex.accepting().len()
        )
        .unwrap();
        write_slice(&mut self.source, regex.accepting());
        self.source.push_str(";\n");
        writeln!(
            self.source,
            "const REGEX_{index}_PLAN: RegexPlan<'static> = match RegexPlan::new(&REGEX_{index}_BYTE_CLASSES, {}, {}, {}, &REGEX_{index}_TRANSITIONS, &REGEX_{index}_ACCEPTING) {{\n    Ok(plan) => plan,\n    Err(_) => panic!(\"compiler emitted invalid regex table\"),\n}};\n",
            regex.state_count(),
            regex.class_count(),
            regex.start_state()
        )
        .unwrap();
    }

    fn write_node(&mut self, index: usize, op: &PlanOp) {
        writeln!(
            self.source,
            "fn node_{index}<'i, S: EventSink<Event = ScalarEvent>>(run: &mut Run<'i, S>, limits: &Limits) -> Step<'i, ()> {{\n    match charge_work(run, limits) {{\n        Step::Matched(()) => {{}},\n        Step::Mismatch(failure) => return Step::Mismatch(failure),\n        Step::Fault(fault) => return Step::Fault(fault),\n    }}"
        )
        .unwrap();
        match op {
            PlanOp::Epsilon => self.source.push_str("    Step::Matched(())\n"),
            PlanOp::Literal(bytes) => {
                self.source.push_str("    match literal(run, &");
                write_slice(&mut self.source, bytes);
                writeln!(
                    self.source,
                    ") {{\n        Step::Matched(span) => emit_event(run, limits, || event(EventKind::Literal, identity(None, Some({index}), None, None), span.start(), span.end(), 0)),\n        Step::Mismatch(failure) => Step::Mismatch(failure),\n        Step::Fault(fault) => Step::Fault(fault),\n    }}"
                )
                .unwrap();
            }
            PlanOp::Regex(regex_index) => {
                writeln!(
                    self.source,
                    "    let terminal = RegexTerminal::new(REGEX_{regex_index}_PLAN);\n    match regex(run, &terminal) {{\n        Step::Matched(span) => emit_event(run, limits, || event(EventKind::Regex, identity(None, Some({index}), None, None), span.start(), span.end(), 0)),\n        Step::Mismatch(failure) => Step::Mismatch(failure),\n        Step::Fault(fault) => Step::Fault(fault),\n    }}"
                )
                .unwrap();
            }
            PlanOp::RuleRef(rule) => {
                writeln!(self.source, "    rule_{}(run, limits)", rule.index()).unwrap();
            }
            PlanOp::Sequence(children) => {
                self.source.push_str("    sequence(run, |run| {\n");
                for child in children {
                    writeln!(
                        self.source,
                        "        match node_{}(run, limits) {{\n            Step::Matched(()) => {{}},\n            Step::Mismatch(failure) => return Step::Mismatch(failure),\n            Step::Fault(fault) => return Step::Fault(fault),\n        }}",
                        child.index()
                    )
                    .unwrap();
                }
                self.source.push_str("        Step::Matched(())\n    })\n");
            }
            PlanOp::Choice(children) => {
                self.source.push_str("    ");
                self.write_choice(index, children, 0, 4);
                self.source.push('\n');
            }
            PlanOp::Repeat {
                child,
                minimum,
                maximum,
            } => {
                let maximum = maximum
                    .map(|value| format!("Some({value}usize)"))
                    .unwrap_or_else(|| "None".to_owned());
                writeln!(
                    self.source,
                    "    let start = run.cursor().offset();\n    match repeat(run, {minimum}usize, {maximum}, |run| node_{}(run, limits)) {{\n        Step::Matched(count) => {{\n            let end = run.cursor().offset();\n            emit_event(run, limits, || event(EventKind::RepeatCount, identity(None, Some({index}), None, None), start, end, u32::try_from(count).unwrap_or(u32::MAX)))\n        }}\n        Step::Mismatch(failure) => Step::Mismatch(failure),\n        Step::Fault(fault) => Step::Fault(fault),\n    }}",
                    child.index()
                )
                .unwrap();
            }
            PlanOp::Record { owner, slots } => {
                self.source.push_str("    sequence(run, |run| {\n");
                for slot in slots {
                    match slot {
                        PlanRecordSlot::Field { field, child } => {
                            writeln!(
                                self.source,
                                "        let field_start_{} = run.cursor().offset();\n        match emit_event(run, limits, || event(EventKind::EnterField, identity(Some({}), Some({}), Some({}), None), field_start_{}, field_start_{}, 0)) {{\n            Step::Matched(()) => {{}},\n            Step::Mismatch(failure) => return Step::Mismatch(failure),\n            Step::Fault(fault) => return Step::Fault(fault),\n        }}\n        match node_{}(run, limits) {{\n            Step::Matched(()) => {{}},\n            Step::Mismatch(failure) => return Step::Mismatch(failure),\n            Step::Fault(fault) => return Step::Fault(fault),\n        }}\n        let field_end_{} = run.cursor().offset();\n        match emit_event(run, limits, || event(EventKind::LeaveField, identity(Some({}), Some({}), Some({}), None), field_start_{}, field_end_{}, 0)) {{\n            Step::Matched(()) => {{}},\n            Step::Mismatch(failure) => return Step::Mismatch(failure),\n            Step::Fault(fault) => return Step::Fault(fault),\n        }}",
                                field.index(),
                                owner.index(),
                                child.index(),
                                field.index(),
                                field.index(),
                                field.index(),
                                child.index(),
                                field.index(),
                                owner.index(),
                                child.index(),
                                field.index(),
                                field.index(),
                                field.index(),
                            )
                            .unwrap();
                        }
                        PlanRecordSlot::Discard { child } => {
                            writeln!(
                                self.source,
                                "        match node_{}(run, limits) {{\n            Step::Matched(()) => {{}},\n            Step::Mismatch(failure) => return Step::Mismatch(failure),\n            Step::Fault(fault) => return Step::Fault(fault),\n        }}",
                                child.index(),
                            )
                            .unwrap();
                        }
                    }
                }
                self.source.push_str("        Step::Matched(())\n    })\n");
            }
            PlanOp::Transform {
                child, transform, ..
            } => {
                writeln!(
                    self.source,
                    "    sequence(run, |run| {{\n        let start = run.cursor().offset();\n        match node_{}(run, limits) {{\n            Step::Matched(()) => {{}},\n            Step::Mismatch(failure) => return Step::Mismatch(failure),\n            Step::Fault(fault) => return Step::Fault(fault),\n        }}\n        let end = run.cursor().offset();\n        emit_event(run, limits, || event(EventKind::Transform, identity(None, Some({index}), None, Some({})), start, end, 0))\n    }})",
                    child.index(),
                    transform.index(),
                )
                .unwrap();
            }
        }
        self.source.push_str("}\n\n");
    }

    fn write_choice(
        &mut self,
        node: usize,
        children: &[super::syntax::PlanNodeId],
        branch: usize,
        indent: usize,
    ) {
        if self.source.exceeded() {
            return;
        }
        if children.len() == 1 {
            self.write_choice_branch(node, children[0].index(), branch, indent);
            return;
        }
        let midpoint = children.len() / 2;
        self.source.push_str("choice(run,\n");
        self.source.push_str(&" ".repeat(indent + 4));
        self.source.push_str("|run| ");
        self.write_choice(node, &children[..midpoint], branch, indent + 4);
        self.source.push_str(",\n");
        self.source.push_str(&" ".repeat(indent + 4));
        self.source.push_str("|run| ");
        self.write_choice(node, &children[midpoint..], branch + midpoint, indent + 4);
        self.source.push('\n');
        self.source.push_str(&" ".repeat(indent));
        self.source.push(')');
    }

    fn write_choice_branch(&mut self, node: usize, child: usize, branch: usize, indent: usize) {
        if self.source.exceeded() {
            return;
        }
        self.source.push_str("{\n");
        self.source.push_str(&" ".repeat(indent + 4));
        writeln!(
            self.source,
            "let start = run.cursor().offset();\n{}match node_{child}(run, limits) {{\n{}    Step::Matched(()) => {{\n{}        let end = run.cursor().offset();\n{}        emit_event(run, limits, || event(EventKind::ChoiceBranch, identity(None, Some({node}), None, None), start, end, {branch}))\n{}    }}\n{}    Step::Mismatch(failure) => Step::Mismatch(failure),\n{}    Step::Fault(fault) => Step::Fault(fault),\n{}}}",
            " ".repeat(indent + 4),
            " ".repeat(indent + 4),
            " ".repeat(indent + 4),
            " ".repeat(indent + 4),
            " ".repeat(indent + 4),
            " ".repeat(indent + 4),
            " ".repeat(indent + 4),
            " ".repeat(indent + 4),
        )
        .unwrap();
        self.source.push_str(&" ".repeat(indent));
        self.source.push('}');
    }

    fn write_rule(&mut self, rule: usize, root: usize) {
        writeln!(
            self.source,
            "fn rule_{rule}<'i, S: EventSink<Event = ScalarEvent>>(run: &mut Run<'i, S>, limits: &Limits) -> Step<'i, ()> {{\n    match charge_work(run, limits) {{\n        Step::Matched(()) => {{}},\n        Step::Mismatch(failure) => return Step::Mismatch(failure),\n        Step::Fault(fault) => return Step::Fault(fault),\n    }}\n    with_depth(run, limits, |run| sequence(run, |run| {{\n        let start = run.cursor().offset();\n        match emit_event(run, limits, || event(EventKind::EnterRule, identity(Some({rule}), None, None, None), start, start, 0)) {{\n            Step::Matched(()) => {{}},\n            Step::Mismatch(failure) => return Step::Mismatch(failure),\n            Step::Fault(fault) => return Step::Fault(fault),\n        }}\n        match node_{root}(run, limits) {{\n            Step::Matched(()) => {{}},\n            Step::Mismatch(failure) => return Step::Mismatch(failure),\n            Step::Fault(fault) => return Step::Fault(fault),\n        }}\n        let end = run.cursor().offset();\n        emit_event(run, limits, || event(EventKind::LeaveRule, identity(Some({rule}), None, None, None), start, end, 0))\n    }}))\n}}\n"
        )
        .unwrap();
    }

    fn write_public_surface(&mut self) {
        let entry = self.plan.entry().index();
        writeln!(
            self.source,
            "fn parse_with_sink<'i, S: EventSink<Event = ScalarEvent>>(\n    input: Input<'i>,\n    sink: S,\n    config: LimitsConfig,\n) -> ModuleResult<'i, S> {{\n    let config = config.bounded();\n    let input_limit = config.input_bytes.min(u32::MAX as usize);\n    let input_too_large = input.len() > input_limit;\n    let limits = Limits::new(config);\n    Run::with_sink(input, sink).parse_module(|run| {{\n        if input_too_large {{\n            return resource_fault(run, ResourceKind::InputBytes, input_limit);\n        }}\n        sequence(run, |run| {{\n            match rule_{entry}(run, &limits) {{\n                Step::Matched(()) => {{}},\n                Step::Mismatch(failure) => return Step::Mismatch(failure),\n                Step::Fault(fault) => return Step::Fault(fault),\n            }}\n            match eof(run) {{\n                Step::Matched(_) => {{}},\n                Step::Mismatch(failure) => return Step::Mismatch(failure),\n                Step::Fault(fault) => return Step::Fault(fault),\n            }}\n            let at = run.cursor().offset();\n            emit_event(run, &limits, || event(EventKind::EndInput, identity(None, None, None, None), at, at, 0))\n        }})\n    }})\n}}\n\n\
             pub fn check(input: &[u8]) -> ModuleResult<'_, NoSink<ScalarEvent>> {{\n    check_with_limits(input, LimitsConfig::default())\n}}\n\n\
             pub fn check_with_limits(input: &[u8], config: LimitsConfig) -> ModuleResult<'_, NoSink<ScalarEvent>> {{\n    parse_with_sink(Input::new(input), NoSink::new(), config)\n}}\n\n\
             pub fn parse_events(input: &[u8]) -> ModuleResult<'_, EventBuffer<'_>> {{\n    parse_events_with_limits(input, LimitsConfig::default())\n}}\n\n\
             pub fn parse_events_with_limits(input: &[u8], config: LimitsConfig) -> ModuleResult<'_, EventBuffer<'_>> {{\n    let source = Input::new(input);\n    parse_with_sink(source, EventBuffer::new(source), config)\n}}\n"
        )
        .unwrap();
    }
}

enum EmitFailure {
    Invariant(String),
    OutputBudget { limit: usize },
}

struct BoundedSource {
    text: String,
    limit: usize,
    exceeded: bool,
}

impl BoundedSource {
    fn new(limit: usize) -> Self {
        Self {
            text: String::new(),
            limit,
            exceeded: false,
        }
    }

    fn push_str(&mut self, value: &str) {
        let _ = std::fmt::Write::write_str(self, value);
    }

    fn push(&mut self, value: char) {
        let _ = std::fmt::Write::write_char(self, value);
    }

    const fn exceeded(&self) -> bool {
        self.exceeded
    }

    fn into_string(self) -> String {
        self.text
    }
}

impl std::fmt::Write for BoundedSource {
    fn write_str(&mut self, value: &str) -> std::fmt::Result {
        if self.exceeded {
            return Ok(());
        }
        let Some(next_len) = self.text.len().checked_add(value.len()) else {
            self.exceeded = true;
            return Ok(());
        };
        if next_len > self.limit {
            self.exceeded = true;
            return Ok(());
        }
        self.text.push_str(value);
        Ok(())
    }
}

fn write_slice<T: std::fmt::Debug>(output: &mut BoundedSource, values: &[T]) {
    output.push('[');
    for (index, value) in values.iter().enumerate() {
        if index != 0 {
            output.push_str(", ");
        }
        write!(output, "{value:?}").unwrap();
    }
    output.push(']');
}
